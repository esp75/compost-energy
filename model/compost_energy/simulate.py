"""Synthetic sensor data for a prototype-scale compost heat-recovery box.

THIS GENERATES SIMULATED DATA, NOT MEASUREMENTS. It exists to (1) show what a
prototype run should look like if the physics in this repo is right, and
(2) give the logging/cleaning/analysis pipeline realistic input, faults
included, before real logger data exists. Real runs go in data/measured/ and
use the same analysis code.

Model (lumped, one thermal node for the pile core):

    C dT/dt = P_bio - P_walls - P_vent - P_hx

    P_bio  = H * k(T) * f_lag(t) * f_O2(t) * S       microbial heat
    dS/dt  = -k(T) * f_lag(t) * f_O2(t) * S          biodegradable solids left
    k(T)   = max(a * CTMI_meso(T), CTMI_thermo(T)) * k_max
             two microbial populations, each a cardinal temperature model
    P_walls = UA_walls * (T - T_amb)
    P_vent  = c_vent * (T - T_amb)^1.5              buoyancy-driven air + latent heat
    P_hx    = m_dot cp (T_out - T_in)                buried pipe, effectiveness-NTU

Turning the pile dumps sensible heat to the air (an instantaneous temperature
drop) and re-oxygenates it (f_O2 resets to 1).
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field

import numpy as np
import pandas as pd

from .heat_exchanger import PipeExchanger

CP_WATER = 4186.0
TEMP_COLUMNS = ["t_core_c", "t_mid_c", "t_ambient_c", "t_water_in_c", "t_water_out_c"]
SIMULATED_BANNER = (
    "SIMULATED DATA - generated by model/compost_energy/simulate.py. "
    "Not a physical measurement."
)


@dataclass
class PileParams:
    wet_mass_kg: float = 200.0  # ~0.5 m3 of mixed food + green waste
    moisture: float = 0.58
    volatile_solids: float = 0.80  # fraction of dry mass
    biodegradable_fraction: float = 0.55  # fraction of VS that can degrade
    heat_of_degradation_j_per_kg: float = 18e6  # per kg of VS oxidised
    k_max_per_day: float = 0.12
    # Mesophiles (start the pile) and thermophiles (do most of the work).
    meso: tuple = (0.0, 38.0, 55.0)  # (t_min, t_opt, t_max)
    meso_weight: float = 0.45
    thermo: tuple = (25.0, 58.0, 71.0)
    lag_days: float = 1.2  # microbial population build-up
    o2_floor: float = 0.55  # rate multiplier once the pile has gone anoxic in places
    o2_decay_days: float = 5.0
    ua_walls: float = 4.0  # W/K, timber box ~3.8 m2 lined with 40 mm insulation
    c_vent: float = 0.5  # W/K^1.5, natural low/high vents (VB/VH)
    turn_days: tuple = (9.5, 23.0)
    turn_drop_k: float = 7.0

    @property
    def heat_capacity_j_per_k(self) -> float:
        cp = self.moisture * CP_WATER + (1 - self.moisture) * 1200.0
        return self.wet_mass_kg * cp

    @property
    def biodegradable_kg(self) -> float:
        return self.wet_mass_kg * (1 - self.moisture) * self.volatile_solids * self.biodegradable_fraction


@dataclass
class LoopParams:
    exchanger: PipeExchanger = field(default_factory=PipeExchanger)
    flow_l_min: float = 0.35  # low flow so the outlet rise is measurable with DS18B20s
    pump_on_hour: float = 9.0
    pump_off_hour: float = 17.0
    start_day: float = 2.0  # loop installed once the pile is active
    tap_temp_c: float = 14.0
    enable_margin_c: float = 8.0  # thermostat: pump only if core > inlet + margin


@dataclass
class RunConfig:
    days: float = 45.0
    dt_s: float = 60.0
    log_every_s: float = 120.0
    t_start: str = "2026-10-01 00:00:00"
    ambient_mean_c: float = 13.0
    ambient_daily_amp_c: float = 5.0
    ambient_trend_c_per_day: float = -0.08  # autumn
    seed: int = 42


def ctmi(t: float, t_min: float, t_opt: float, t_max: float) -> float:
    """Rosso cardinal temperature model, normalised to 1 at t_opt."""
    if t <= t_min or t >= t_max:
        return 0.0
    num = (t - t_max) * (t - t_min) ** 2
    den = (t_opt - t_min) * ((t_opt - t_min) * (t - t_opt) - (t_opt - t_max) * (t_opt + t_min - 2 * t))
    return max(num / den, 0.0)


def rate_factor(t: float, pile: PileParams) -> float:
    return max(pile.meso_weight * ctmi(t, *pile.meso), ctmi(t, *pile.thermo))


def _pump_on(day: float, loop: LoopParams) -> bool:
    hour = (day % 1.0) * 24.0
    return day >= loop.start_day and loop.pump_on_hour <= hour < loop.pump_off_hour


def simulate_truth(pile: PileParams | None = None, loop: LoopParams | None = None, cfg: RunConfig | None = None):
    """Integrate the physics. Returns (truth dataframe at log rate, energy ledger)."""
    pile = pile or PileParams()
    loop = loop or LoopParams()
    cfg = cfg or RunConfig()
    rng = np.random.default_rng(cfg.seed)

    n = int(cfg.days * 86400 / cfg.dt_s)
    log_stride = int(cfg.log_every_s / cfg.dt_s)
    C = pile.heat_capacity_j_per_k
    hx = loop.exchanger
    m_cp_loop = loop.flow_l_min / 60.0 * CP_WATER

    # Weather: AR(1) anomaly on top of a daily cycle and a seasonal trend.
    weather = 0.0
    phi = math.exp(-cfg.dt_s / (2.5 * 86400))
    weather_sigma = 2.0 * math.sqrt(1 - phi**2)

    T = cfg.ambient_mean_c + 2.0  # fresh pile, slightly above ambient
    T0 = T
    S = pile.biodegradable_kg
    t_mid = T
    last_turn = 0.0
    turns_done = set()
    ledger = dict(bio_j=0.0, walls_j=0.0, vent_j=0.0, hx_j=0.0, turning_j=0.0)
    rows = []

    for i in range(n):
        day = i * cfg.dt_s / 86400.0
        weather = phi * weather + weather_sigma * rng.standard_normal()
        t_amb = (
            cfg.ambient_mean_c
            + cfg.ambient_trend_c_per_day * day
            + cfg.ambient_daily_amp_c * math.sin(2 * math.pi * (day - 0.375))
            + weather
        )

        for td in pile.turn_days:
            if td not in turns_done and day >= td:
                turns_done.add(td)
                last_turn = day
                drop = min(pile.turn_drop_k, max(T - t_amb, 0.0))
                ledger["turning_j"] += C * drop
                T -= drop

        f_lag = 1.0 - math.exp(-day / pile.lag_days)
        f_o2 = pile.o2_floor + (1 - pile.o2_floor) * math.exp(-(day - last_turn) / pile.o2_decay_days)
        k = pile.k_max_per_day / 86400.0 * rate_factor(T, pile) * f_lag * f_o2
        dS = k * S * cfg.dt_s
        p_bio = dS * pile.heat_of_degradation_j_per_kg / cfg.dt_s

        dT_amb = T - t_amb
        p_walls = pile.ua_walls * dT_amb
        p_vent = pile.c_vent * max(dT_amb, 0.0) ** 1.5

        t_in = 0.6 * loop.tap_temp_c + 0.4 * t_amb
        pump = _pump_on(day, loop) and T > t_in + loop.enable_margin_c
        if pump:
            t_out = hx.outlet_temperature(T, t_in, loop.flow_l_min)
            p_hx = m_cp_loop * (t_out - t_in)
        else:
            t_out = float("nan")
            p_hx = 0.0

        T += (p_bio - p_walls - p_vent - p_hx) * cfg.dt_s / C
        S -= dS
        # Mid-depth probe: between core and ambient, lagging by ~3 h.
        t_mid += (t_amb + 0.78 * (T - t_amb) - t_mid) * cfg.dt_s / (3 * 3600)

        ledger["bio_j"] += p_bio * cfg.dt_s
        ledger["walls_j"] += p_walls * cfg.dt_s
        ledger["vent_j"] += p_vent * cfg.dt_s
        ledger["hx_j"] += p_hx * cfg.dt_s

        if i % log_stride == 0:
            rows.append((day, T, t_mid, t_amb, t_in, t_out, loop.flow_l_min if pump else 0.0, p_bio, p_hx, S))

    ledger["stored_j"] = C * (T - T0)
    ledger["degraded_kg"] = pile.biodegradable_kg - S
    truth = pd.DataFrame(
        rows,
        columns=["day", "t_core_c", "t_mid_c", "t_ambient_c", "t_water_in_c", "t_water_out_c",
                 "flow_l_min", "p_bio_w", "p_hx_w", "substrate_kg"],
    )
    truth.insert(0, "timestamp", pd.Timestamp(cfg.t_start) + pd.to_timedelta(truth["day"], unit="D"))
    return truth, ledger


def to_sensor_log(truth: pd.DataFrame, cfg: RunConfig | None = None) -> pd.DataFrame:
    """Turn ground truth into what an ESP32 + DS18B20 logger would actually write."""
    cfg = cfg or RunConfig()
    rng = np.random.default_rng(cfg.seed + 1)
    df = truth[["timestamp", "day", "t_core_c", "t_mid_c", "t_ambient_c", "t_water_in_c",
                "t_water_out_c", "flow_l_min"]].copy()
    n = len(df)
    pump = df["flow_l_min"].to_numpy() > 0
    amb = df["t_ambient_c"].to_numpy()

    # Water-line probes sit on the pipe outside the pile: with no flow they drift
    # toward ambient; when the pump starts they respond with a ~2 min lag.
    for col, idle_offset in (("t_water_in_c", 0.5), ("t_water_out_c", 2.0)):
        x = df[col].to_numpy().copy()
        out = np.empty(n)
        state = amb[0]
        alpha_flow = 1 - math.exp(-cfg.log_every_s / 120.0)
        alpha_idle = 1 - math.exp(-cfg.log_every_s / 1200.0)
        for i in range(n):
            target = x[i] if pump[i] else amb[i] + idle_offset
            state += (target - state) * (alpha_flow if pump[i] else alpha_idle)
            out[i] = state
        df[col] = out

    # DS18B20: ~0.1 C noise, 0.0625 C resolution.
    for col in TEMP_COLUMNS:
        noisy = df[col].to_numpy() + rng.normal(0, 0.1, n)
        df[col] = np.round(noisy / 0.0625) * 0.0625

    # Hall-effect flow sensor: a few % jitter, pulses quantised to 0.01 L/min.
    flow = df["flow_l_min"].to_numpy()
    df["flow_l_min"] = np.round(np.where(pump, flow * (1 + rng.normal(0, 0.03, n)), 0.0), 2)

    # Headspace humidity: near-saturated while the pile is hot and wet.
    core = truth["t_core_c"].to_numpy()
    rh = 88 + 10 * np.tanh((core - 30) / 12) + rng.normal(0, 1.2, n)
    df["rh_pct"] = np.round(np.clip(rh, 40, 99.9), 1)

    # ---- faults -------------------------------------------------------
    faults = {}
    # DS18B20 error codes: -127 = probe disconnected/CRC fail, 85 = read before conversion.
    for col in TEMP_COLUMNS:
        idx127 = rng.choice(n, size=int(0.0015 * n), replace=False)
        idx85 = rng.choice(n, size=int(0.0005 * n), replace=False)
        df.loc[df.index[idx127], col] = -127.0
        df.loc[df.index[idx85], col] = 85.0
        faults[f"sentinel_{col}"] = len(set(idx127) | set(idx85))

    # Mid probe sticks (I2C/OneWire bus lock-up) for 1.5 days.
    stuck = (df["day"] >= 17.0) & (df["day"] < 18.5)
    df.loc[stuck, "t_mid_c"] = df.loc[stuck, "t_mid_c"].iloc[0]
    faults["stuck_t_mid_rows"] = int(stuck.sum())

    # Flow sensor glitches (air bubble / EMI).
    on_idx = np.flatnonzero(pump)
    spikes = rng.choice(on_idx, size=12, replace=False)
    df.loc[df.index[spikes], "flow_l_min"] = np.round(df["flow_l_min"].iloc[spikes] * rng.uniform(8, 15, 12), 2)
    faults["flow_spikes"] = 12

    # Partial line writes.
    blank = rng.choice(n, size=int(0.0005 * n), replace=False)
    df.loc[df.index[blank], "rh_pct"] = np.nan

    # Logger power losses: rows simply missing.
    gaps = [(6.20, 6.24), (20.50, 20.75), (31.10, 31.12)]
    keep = np.ones(n, dtype=bool)
    for a, b in gaps:
        keep &= ~((df["day"] >= a) & (df["day"] < b)).to_numpy()
    faults["gap_rows_removed"] = int((~keep).sum())
    df = df[keep]

    # RTC jitter and duplicated writes after Wi-Fi reconnects.
    df["timestamp"] = df["timestamp"] + pd.to_timedelta(rng.uniform(-4, 4, len(df)), unit="s")
    dup = df.sample(frac=0.004, random_state=cfg.seed)
    faults["duplicate_rows"] = len(dup)
    df = pd.concat([df, dup]).sort_values("timestamp", kind="stable")
    # A handful of rows land out of order (buffer flushed late).
    df = df.reset_index(drop=True)
    swap = rng.choice(len(df) - 1, size=20, replace=False)
    order = np.arange(len(df))
    order[swap], order[swap + 1] = order[swap + 1], order[swap]
    df = df.iloc[order]

    df = df.drop(columns="day")
    df["timestamp"] = df["timestamp"].dt.strftime("%Y-%m-%dT%H:%M:%S")
    df.attrs["faults"] = faults
    return df


def write_log(df: pd.DataFrame, path, seed: int) -> None:
    with open(path, "w") as f:
        f.write(f"# {SIMULATED_BANNER}\n")
        f.write(f"# seed={seed}; columns: temperatures in C (DS18B20), flow in L/min, rh in %\n")
        df.to_csv(f, index=False, float_format="%.4g")
